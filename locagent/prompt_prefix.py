"""System prompt 构建。

使用接口原生的工具调用后，工具定义通过请求的 tools 参数单独发送，
模型按接口格式返回工具调用，不再需要在 prompt 里教它“怎么写调用格式”。
这里只剩下：它是谁、做事的规则、当前工作区的稳定信息。
同一次运行里这部分基本不变，和工具定义一起位于请求最前面，便于缓存。
"""

import hashlib
import json
import os
import textwrap
from dataclasses import dataclass

from .workspace import now


@dataclass
class PromptPrefix:
    # 除了文本本身，还带一小份元数据，
    # 后续步骤据此判断 system prompt 或工具集合是否变化（缓存、中断恢复）。
    text: str
    hash: str
    workspace_fingerprint: str
    tool_signature: str
    built_at: str


def tool_signature(tools):
    # 工具集合的指纹：开放的工具或其定义变了，指纹就会变
    payload = []
    for name in sorted(tools):
        tool = tools[name]
        payload.append(
            {
                "name": name,
                "input_schema": tool["input_schema"],
                "risky": tool["risky"],
                "description": tool["description"],
            }
        )
    return hashlib.sha256(json.dumps(payload, sort_keys=True).encode("utf-8")).hexdigest()


SYSTEM_RULES = textwrap.dedent(
    """\
    You are LocAgent, a small local coding agent working inside a local workspace.

    Rules:
    - Use the provided tools instead of guessing about the workspace.
    - Never invent tool results.
    - When you call tools, first write one short sentence: what is done so far and what you will do next. It is saved as your progress note.
    - When the task is done, reply with a concise, concrete answer and no tool call.
    - Write your progress notes and answers in the same language as the user's request, even though runtime notices are in English.
    - If the user asks you to create or update a specific file and the path is clear, use write_file or patch_file instead of repeatedly listing files.
    - Before writing tests for existing code, read the implementation first.
    - When writing tests, match the current implementation unless the user explicitly asked you to change the code.
    - New files should be complete and runnable, including obvious imports.
    - Do not repeat the same tool call with the same arguments if it did not help. Choose a different tool or answer.
    - Each user message starts with a <workspace_status> block generated by the runtime; it is not written by the user.
    - A <conversation_summary> block replaces earlier turns that were compacted; treat it as what happened before.
    - Old tool results may be replaced by a short "[old result cleared ...]" note; call the tool again if you need the content.
    """
).strip()


def tool_rules(tools):
    # 只写本次开放的工具相关的规则：提到未开放的工具，模型会去调用然后被拒绝
    rules = []
    if "write_file" in tools and "patch_file" in tools:
        # 单次回复的输出有上限（max_new_tokens），工具参数里的文件内容也算在内。
        # 模型不知道这个上限时，会先尝试一次写完长文件，被截断后整段作废（2026-10-15 评测发现）
        rules.append(
            "- Each response has an output token limit, and tool arguments count toward it. "
            "Write a file longer than about 200 lines in parts from the start: "
            "write_file for the first part, then patch_file to append the rest."
        )
    if "search" in tools:
        rules.append("- Use search to find code instead of reading files one by one.")
    if "update_todos" in tools:
        rules.append("- For tasks with 3 or more steps, plan them with update_todos first and keep the list current as you work.")
    if "run_shell" in tools:
        rules.append("- After changing code, run it or its tests with run_shell when that is possible, and fix failures before answering.")
        # 告诉模型命令在什么系统、什么 shell 里执行，否则它可能在 Windows 上写出 ls、rm 这类 Linux 命令
        if os.name == "nt":
            rules.append("- run_shell uses cmd.exe on Windows: use Windows commands (dir, type) or python, not ls/cat/rm.")
        else:
            rules.append("- run_shell uses /bin/sh.")
    return "\n".join(rules)


def build_prompt_prefix(workspace, tools, built_at=None):
    extra = tool_rules(tools)
    text = SYSTEM_RULES + ("\n" + extra if extra else "") + "\n\n" + workspace.text()
    return PromptPrefix(
        text=text,
        hash=hashlib.sha256(text.encode("utf-8")).hexdigest(),
        workspace_fingerprint=workspace.fingerprint(),
        tool_signature=tool_signature(tools),
        built_at=built_at or now(),
    )
